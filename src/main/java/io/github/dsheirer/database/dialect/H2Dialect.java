package io.github.dsheirer.database.dialect;

import io.github.dsheirer.database.DatabaseConfiguration;

import java.nio.file.Path;

/**
 * Built-in H2 embedded database, stored in the application 'db' directory.
 */
public class H2Dialect implements IDatabaseDialect
{
    public static final String DATABASE_FILE_NAME = "sdrtrunk";

    @Override
    public String getDriverClass()
    {
        return "org.h2.Driver";
    }

    @Override
    public int getDefaultPort()
    {
        return 0;
    }

    @Override
    public boolean isNetwork()
    {
        return false;
    }

    @Override
    public boolean requiresDatabaseName()
    {
        return false;
    }

    @Override
    public String getJdbcUrl(DatabaseConfiguration configuration, Path databaseDirectory)
    {
        //DB_CLOSE_ON_EXIT=FALSE: the application closes the pool during shutdown, after the last call update.
        return "jdbc:h2:file:" + databaseDirectory.resolve(DATABASE_FILE_NAME).toAbsolutePath() +
            ";DB_CLOSE_ON_EXIT=FALSE";
    }

    @Override
    public String getIdentityColumn()
    {
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    }

    @Override
    public String getLargeTextColumn()
    {
        return "CLOB";
    }

    @Override
    public String getDropSchemaStatement(String schema)
    {
        return "DROP SCHEMA IF EXISTS " + schema + " CASCADE";
    }
}
